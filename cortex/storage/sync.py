#!/usr/bin/env python3
"""
sync.py — best-effort push of the local SQLite store up to the remote Supabase
Postgres, for backup + cross-device. The "keep sync" half of local-first.

Design (deliberately simple + safe for a mostly-single-writer personal agent):
  * Only ever pushes LOCAL -> REMOTE. SQLite is the source of truth.
  * Small STATE tables (memory, priorities, goals, reminders, projects, plans)
    are fully upserted each run (catches edits like a goal marked done).
  * Large APPEND tables (experiences, conversations, autonomy_log, command_log)
    push only rows newer than a per-table high-water mark (~/.cortex/state/sync.json).
  * Skips entirely (no error) when the remote is unreachable — e.g. Tailscale off.
  * context_store is never synced (ephemeral, regenerated by collectors).

Run:  python3 sync.py          (or: run_once.py sync)
"""
from __future__ import annotations

import os
import sys
import json
import logging

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(name)s] %(levelname)s: %(message)s",
                    datefmt="%H:%M:%S")
log = logging.getLogger("cortex.sync")

os.chdir(__import__("cortex").ROOT)
from cortex.util.cortex_bootstrap import load_config, load_secrets, ensure_state_dir

_HWM_FILE = os.path.expanduser("~/.cortex/state/sync.json")

# column_name -> pg cast suffix for columns that aren't plain scalars
_JSON_COLS = {"value", "state_context", "action_payload", "context_snapshot",
              "custom_commands", "steps", "results"}
_VEC_COLS = {"embedding"}
# SQLite has no bool type (stores 0/1); Postgres columns are boolean. Convert to
# real Python bools so psycopg2 adapts them (PG rejects a direct int->bool cast).
_BOOL_COLS = {"fired", "was_corrected", "was_confirmed", "needs_confirmation",
              "confirmed", "notified", "collect_git", "collect_deps"}

STATE_TABLES = ["memory", "priorities", "goals", "reminders", "tracked_projects", "devops_plans"]
APPEND_TABLES = ["experiences", "conversations", "autonomy_log", "command_log"]


def _load_hwm() -> dict:
    try:
        with open(_HWM_FILE, encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, ValueError):
        return {}


def _save_hwm(hwm: dict):
    ensure_state_dir()
    with open(_HWM_FILE, "w", encoding="utf-8") as f:
        json.dump(hwm, f)


def _cols(slite, table) -> list[str]:
    return [r[1] for r in slite.execute(f"PRAGMA table_info({table})").fetchall()]


def _val_and_cast(col, v):
    """Return (param_value, placeholder) for one column, handling json/vector/bool."""
    if col in _VEC_COLS:
        return v, "%s::vector"       # SQLite already stores '[...]' text
    if col in _JSON_COLS:
        if v is None:
            return None, "%s::jsonb"
        return (v if isinstance(v, str) else json.dumps(v)), "%s::jsonb"
    if col in _BOOL_COLS:
        return (None if v is None else bool(v)), "%s"
    return v, "%s"


def _push_table(slite, pg, table, cols, rows, upsert: bool) -> int:
    pushed = 0
    with pg.cursor() as cur:
        for row in rows:
            d = dict(row)
            names, marks, params = [], [], []
            for c in cols:
                if c not in d:
                    continue
                pv, mark = _val_and_cast(c, d[c])
                names.append(c); marks.append(mark); params.append(pv)
            collist = ", ".join(names)
            marklist = ", ".join(marks)
            if upsert:
                setlist = ", ".join(f"{c}=EXCLUDED.{c}" for c in names if c != "id")
                sql = (f"INSERT INTO {table} ({collist}) VALUES ({marklist}) "
                       f"ON CONFLICT (id) DO UPDATE SET {setlist}")
            else:
                sql = f"INSERT INTO {table} ({collist}) VALUES ({marklist}) ON CONFLICT (id) DO NOTHING"
            try:
                cur.execute(sql, params)
                pushed += 1
            except Exception as e:
                pg.rollback()
                log.warning(f"  {table} row {d.get('id')} skipped: {e}")
        pg.commit()
    return pushed


def main() -> int:
    load_secrets()
    config = load_config()
    dbc = config["database"]

    import cortex.storage.sqlite_backend as sqlite_backend
    sqlite_path = os.path.expanduser(dbc.get("sqlite_path", "~/.cortex/cortex.db"))
    slite = sqlite_backend.open_db(sqlite_path)

    import psycopg2
    from psycopg2 import extras
    pw = dbc.get("password") or os.environ.get("CORTEX_DB_PASSWORD", "")
    if not pw:
        log.info("no remote password available — skipping sync")
        return 0
    try:
        pg = psycopg2.connect(host=dbc["host"], port=dbc["port"], dbname=dbc["name"],
                              user=dbc["user"], password=pw, connect_timeout=8)
    except Exception as e:
        log.info(f"remote unreachable (Tailscale off?) — skipping sync: {e}")
        return 0
    pg.cursor_factory = extras.RealDictCursor

    hwm = _load_hwm()
    total = 0

    for table in STATE_TABLES:
        cols = _cols(slite, table)
        rows = slite.execute(f"SELECT * FROM {table}").fetchall()
        if rows:
            total += _push_table(slite, pg, table, cols, rows, upsert=True)
        log.info(f"  {table}: {len(rows)} upserted")

    for table in APPEND_TABLES:
        cols = _cols(slite, table)
        last = int(hwm.get(table, 0))
        rows = slite.execute(f"SELECT * FROM {table} WHERE id > ? ORDER BY id", (last,)).fetchall()
        if rows:
            total += _push_table(slite, pg, table, cols, rows, upsert=False)
            hwm[table] = rows[-1]["id"]
        log.info(f"  {table}: {len(rows)} new (hwm now {hwm.get(table, last)})")

    _save_hwm(hwm)
    slite.close()
    pg.close()
    log.info(f"sync done — {total} rows pushed to remote")
    return 0


if __name__ == "__main__":
    sys.exit(main())
